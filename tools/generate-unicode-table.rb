#!/usr/bin/env ruby
#
# Generates src/unicode-table.c from the Unicode Character Database (UCD).
# Use "rake unicode:update VERSION=..." to update src/unicode-table.c:
#
#   tools/generate-unicode-table.rb VERSION > src/unicode-table.c
#   tools/generate-unicode-table.rb UCD_DIRECTORY > src/unicode-table.c
#
# The UCD files of VERSION such as 16.0.0 are downloaded from
# https://www.unicode.org/Public/VERSION/ucd/ . UCD_DIRECTORY must have
# the same files instead.
#
# ASCII characters aren't included because they are processed without the
# tables.

require "open-uri"

source = ARGV[0] or abort("Usage: #{$0} VERSION|UCD_DIRECTORY")

def read_ucd(source, name)
  if File.directory?(source)
    File.read(File.join(source, name))
  else
    URI.open("https://www.unicode.org/Public/#{source}/ucd/#{name}", &:read)
  end
end

def each_entry(content)
  content.each_line do |line|
    line = line.sub(/#.*/, "").strip
    next if line.empty?
    yield(line.split(";", -1).collect(&:strip))
  end
end

def parse_codes(codes)
  codes.split.collect {|code| code.to_i(16)}
end

def read_property(content, name)
  codes = []
  each_entry(content) do |range, property|
    next unless property == name
    first, last = range.split("..").collect {|code| code.to_i(16)}
    codes.concat((first..(last || first)).to_a)
  end
  codes.select {|code| code >= 0x80}.sort
end

# Returns [first, last, step, value] runs of the sorted CODES. A run has the
# codes FIRST, FIRST + STEP, ..., LAST that have the same VALUE of the
# block. STEP is 1 or 2.
def runs(codes)
  result = []
  codes.each do |code|
    value = block_given? ? yield(code) : nil
    run = result.last
    if run and run[3] == value and
        (run[2] ? code - run[1] == run[2] : (code - run[1]).between?(1, 2))
      run[2] ||= code - run[1]
      run[1] = code
    else
      result << [code, code, nil, value]
    end
  end
  result.collect {|first, last, step, value| [first, last, step || 1, value]}
end

derived_core_properties = read_ucd(source, "DerivedCoreProperties.txt")
version = derived_core_properties[/\d+\.\d+\.\d+/]
prop_list = read_ucd(source, "PropList.txt")
unicode_data = {}
each_entry(read_ucd(source, "UnicodeData.txt")) do |fields|
  unicode_data[fields[0].to_i(16)] = fields
end

properties = {
  "alphabetic" => read_property(derived_core_properties, "Alphabetic"),
  "uppercase" => read_property(derived_core_properties, "Uppercase"),
  "lowercase" => read_property(derived_core_properties, "Lowercase"),
  "whitespace" => read_property(prop_list, "White_Space"),
}
decimal_digits = unicode_data.select {|code, fields|
  code >= 0x80 and fields[2] == "Nd"
}
properties["decimal_digit"] = decimal_digits.keys.sort
# digit-value assumes that each run of decimal digits starts with zero.
runs(properties["decimal_digit"]).each do |first, last, step|
  first.step(last, step) do |code|
    unless step == 1 and decimal_digits[code][6].to_i == (code - first) % 10
      abort("unexpected decimal digit: U+%04X" % code)
    end
  end
end

simple_mappings = {"upcase" => {}, "downcase" => {}, "foldcase" => {}}
unicode_data.each do |code, fields|
  next if code < 0x80
  simple_mappings["upcase"][code] = fields[12].to_i(16) unless fields[12].empty?
  simple_mappings["downcase"][code] = fields[13].to_i(16) unless fields[13].empty?
end

full_mappings = {"upcase" => {}, "downcase" => {}, "foldcase" => {}}
each_entry(read_ucd(source, "CaseFolding.txt")) do |code, status, mapping|
  code = code.to_i(16)
  next if code < 0x80
  case status
  when "C", "S"
    simple_mappings["foldcase"][code] = parse_codes(mapping)[0]
  when "F"
    full_mappings["foldcase"][code] = parse_codes(mapping)
  end
end
special_casing = read_ucd(source, "SpecialCasing.txt")
each_entry(special_casing) do |code, lower, title, upper, condition|
  # Language-sensitive and context-sensitive mappings aren't supported.
  next unless condition.empty?
  code = code.to_i(16)
  next if code < 0x80
  {"downcase" => lower, "upcase" => upper}.each do |name, mapping|
    mapping = parse_codes(mapping)
    full_mappings[name][code] = mapping if mapping.size > 1
  end
end
# SCM_UNICODE_FULL_CASE_MAX in src/sigschemeinternal.h
full_mappings.each_value do |mapping|
  abort("too long full case mapping") if mapping.values.any? {|m| m.size > 3}
end

# Bits of 256-character blocks that have characters with case mappings.
case_codes = (simple_mappings.values + full_mappings.values).flat_map(&:keys)
case_blocks = Array.new((case_codes.max >> 8) / 8 + 1, 0)
case_codes.each do |code|
  block = code >> 8
  case_blocks[block / 8] |= 1 << (block % 8)
end

puts(<<-HEADER)
/* This file is generated by tools/generate-unicode-table.rb from the
 * Unicode Character Database #{version}. Don't edit directly.
 *
 * The Unicode Character Database is covered by the Unicode License V3. See
 * COPYING. */
HEADER

properties.each do |name, codes|
  puts
  puts("static const unicode_range #{name}_ranges[] = {")
  runs(codes).each do |first, last, step|
    puts("    {0x%04X, 0x%04X, %d}," % [first, last, step])
  end
  puts("};")
end

simple_mappings.each do |name, mapping|
  puts
  puts("static const unicode_mapping #{name}_mappings[] = {")
  runs(mapping.keys.sort) {|code| mapping[code] - code}.each do |first, last, step, delta|
    puts("    {{0x%04X, 0x%04X, %d}, %d}," % [first, last, step, delta])
  end
  puts("};")
end

puts
puts("static const unsigned char case_blocks[] = {")
case_blocks.each_slice(12) do |bytes|
  puts("    " + bytes.collect {|byte| "0x%02X," % byte}.join(" "))
end
puts("};")

full_mappings.each do |name, mapping|
  puts
  puts("static const unicode_full_mapping full_#{name}_mappings[] = {")
  mapping.keys.sort.each do |code|
    chars = mapping[code].collect {|c| "0x%04X" % c}.join(", ")
    puts("    {0x%04X, {%s}}," % [code, chars])
  end
  puts("};")
end
